/**
 * VERITAS — report export (jury fix W11).
 * A report must leave the atelier, not just live on screen: every batch can be
 * downloaded as Markdown or JSON. reportToMarkdown is pure (tested headlessly);
 * download helpers touch browser APIs only when they exist.
 */

const VERDICT_SCORE = { FRESH: 100, UNCONFIRMED: 50, STALE: 15, CONTRADICTED: 0 }

/** Renders a freshness report as a self-contained Markdown document. */
export function reportToMarkdown(report) {
  const r = report || {}
  const lines = []
  lines.push('# VERITAS — Freshness Report')
  lines.push('')
  lines.push(`- **Examined:** ${r.examinedAt || 'n/a'}`)
  lines.push(`- **Mode:** ${r.mode === 'live' ? 'Live Web' : 'Demo Archive'}${r.gateway ? ` (${r.gateway})` : ''}`)
  if (Number.isInteger(r.aiAssessed)) {
    const total = (r.claims || []).length
    lines.push(`- **AI assessed:** ${r.aiAssessed}/${total} claims`)
  }
  lines.push(`- **Freshness index:** ${r.index}/100 — *${r.verdictLabel || ''}*`)
  lines.push('')
  if (r.summary) {
    lines.push(`> ${r.summary}`)
    lines.push('')
  }
  const claims = r.claims || []
  claims.forEach((c, i) => {
    lines.push(`## ${i + 1}. ${c.verdict} — confidence ${c.confidence}% (${c.type})`)
    lines.push('')
    lines.push(`> "${c.claim}"`)
    lines.push('')
    if (c.explanation) lines.push(`${c.explanation}`)
    if (c.fresher) {
      lines.push('')
      lines.push(`**Fresher data:** ${c.fresher}`)
    }
    if (c.searchError) {
      lines.push('')
      lines.push(`*Search error:* ${c.searchError}`)
    }
    const evidence = c.evidence || []
    if (evidence.length > 0) {
      lines.push('')
      lines.push('**Evidence:**')
      for (const e of evidence) {
        const label = e.url ? `[${e.title}](${e.url})` : `${e.title} *(archived record — link unavailable)*`
        lines.push(`- ${label} — ${e.year}`)
      }
    }
    lines.push('')
  })
  lines.push('---')
  lines.push('')
  lines.push('*Generated by VERITAS — the freshness atelier for AI answers. ' +
    `Index is the mean verdict score (${Object.entries(VERDICT_SCORE).map(([k, v]) => `${k} ${v}`).join(', ')}).*`)
  return lines.join('\n')
}

/** Triggers a browser download for the given text payload. */
export function downloadText(filename, content, mime = 'text/plain') {
  if (typeof document === 'undefined') return false
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
  return true
}

/** Short, sortable stamp for export filenames, e.g. 2026-11-17_14-05. */
export function exportStamp(iso) {
  const d = iso ? new Date(iso) : new Date()
  if (Number.isNaN(d.getTime())) return 'report'
  const p = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}_${p(d.getHours())}-${p(d.getMinutes())}`
}
